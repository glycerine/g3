// mkMul is mk_mul(s, rm, x, y, result).
func (c *FPA2BVConverter) mkMul(s ast.ASTHandle, rm, x, y, result *eref) {
	f := c.frame()
	defer f.done()
	nan, nzero, pzero, ninf, pinf := f.ref(), f.ref(), f.ref(), f.ref(), f.ref()
	c.mkNanSort(s, nan)
	c.mkNzeroSort(s, nzero)
	c.mkPzeroSort(s, pzero)
	c.mkNinfSort(s, ninf)
	c.mkPinfSort(s, pinf)
	xIsNan, xIsZero, xIsPos, xIsInf := f.ref(), f.ref(), f.ref(), f.ref()
	yIsNan, yIsZero, yIsPos, yIsInf := f.ref(), f.ref(), f.ref(), f.ref()
	c.mkIsNan(x.get(), xIsNan)
	c.mkIsZero(x.get(), xIsZero)
	c.mkIsPos(x.get(), xIsPos)
	c.mkIsInf(x.get(), xIsInf)
	c.mkIsNan(y.get(), yIsNan)
	c.mkIsZero(y.get(), yIsZero)
	c.mkIsPos(y.get(), yIsPos)
	c.mkIsInf(y.get(), yIsInf)
	c1, c2, c3, c4, c5, c6 := f.ref(), f.ref(), f.ref(), f.ref(), f.ref(), f.ref()
	v1, v2, v3, v4, v5, v6, v7 := f.ref(), f.ref(), f.ref(), f.ref(), f.ref(), f.ref(), f.ref()
	c.simpOr(c1, xIsNan.get(), yIsNan.get())
	v1.set(nan.get())
	c.mkIsPinf(x.get(), c2)
	ySgnInf := f.ref()
	c.mkIte(yIsPos.get(), pinf.get(), ninf.get(), ySgnInf)
	c.mkIte(yIsZero.get(), nan.get(), ySgnInf.get(), v2)
	c.mkIsPinf(y.get(), c3)
	xSgnInf := f.ref()
	c.mkIte(xIsPos.get(), pinf.get(), ninf.get(), xSgnInf)
	c.mkIte(xIsZero.get(), nan.get(), xSgnInf.get(), v3)
	c.mkIsNinf(x.get(), c4)
	negYSgnInf := f.ref()
	c.mkIte(yIsPos.get(), ninf.get(), pinf.get(), negYSgnInf)
	c.mkIte(yIsZero.get(), nan.get(), negYSgnInf.get(), v4)
	c.mkIsNinf(y.get(), c5)
	negXSgnInf := f.ref()
	c.mkIte(xIsPos.get(), ninf.get(), pinf.get(), negXSgnInf)
	c.mkIte(xIsZero.get(), nan.get(), negXSgnInf.get(), v5)
	c.simpOr(c6, xIsZero.get(), yIsZero.get())
	signXor := f.ref()
	c.simpXor(xIsPos.get(), yIsPos.get(), signXor)
	c.mkIte(signXor.get(), nzero.get(), pzero.get(), v6)
	sbits := c.sbits(s)
	aSgn, aSig, aExp, aLz, bSgn, bSig, bExp, bLz := f.ref(), f.ref(), f.ref(), f.ref(), f.ref(), f.ref(), f.ref(), f.ref()
	c.unpack(x.get(), aSgn, aSig, aExp, aLz, true)
	c.unpack(y.get(), bSgn, bSig, bExp, bLz, true)
	aLzExt, bLzExt := f.ref(), f.ref()
	aLzExt.set(c.zeroExtend(2, aLz.get()))
	bLzExt.set(c.zeroExtend(2, bLz.get()))
	aSigExt, bSigExt := f.ref(), f.ref()
	aSigExt.set(c.zeroExtend(sbits, aSig.get()))
	bSigExt.set(c.zeroExtend(sbits, bSig.get()))
	aExpExt, bExpExt := f.ref(), f.ref()
	aExpExt.set(c.signExtend(2, aExp.get()))
	bExpExt.set(c.signExtend(2, bExp.get()))
	resSgn, resSig, resExp := f.ref(), f.ref(), f.ref()
	resSgn.set(c.bvXor(aSgn.get(), bSgn.get()))
	r := c.bvSub(bExpExt.get(), bLzExt.get())
	l := c.bvSub(aExpExt.get(), aLzExt.get())
	resExp.set(c.bvAdd(l, r))
	product := f.ref()
	product.set(c.bvMul(aSigExt.get(), bSigExt.get()))
	hP, lP, rbits := f.ref(), f.ref(), f.ref()
	hP.set(c.extract(2*sbits-1, sbits, product.get()))
	lP.set(c.extract(sbits-1, 0, product.get()))
	if sbits >= 4 {
		g := c.frame()
		sticky := g.ref()
		sticky.set(c.redor(c.extract(sbits-4, 0, product.get())))
		rbits.set(c.concat(c.extract(sbits-1, sbits-3, product.get()), sticky.get()))
		g.done()
	} else {
		rbits.set(c.concat(lP.get(), c.bvNum(0, 4-sbits)))
	}
	resSig.set(c.concat(hP.get(), rbits.get()))
	c.round(s, rm, resSgn, resSig, resExp, v7)
	c.mkIte(c6.get(), v6.get(), v7.get(), result)
	c.mkIte(c5.get(), v5.get(), result.get(), result)
	c.mkIte(c4.get(), v4.get(), result.get(), result)
	c.mkIte(c3.get(), v3.get(), result.get(), result)
	c.mkIte(c2.get(), v2.get(), result.get(), result)
	c.mkIte(c1.get(), v1.get(), result.get(), result)
}

