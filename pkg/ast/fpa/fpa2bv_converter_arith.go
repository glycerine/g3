// addCore is add_core(sbits, ebits, c_*, d_*, res_*).
func (c *FPA2BVConverter) addCore(sbits, ebits uint32, cSgn, cSig, cExp, dSgn, dSig, dExp, resSgn, resSig, resExp *eref) {
	f := c.frame()
	defer f.done()
	expDelta := f.ref()
	expDelta.set(c.bvSub(cExp.get(), dExp.get()))
	if math.Log2(float64(sbits+2)) < float64(ebits+2) {
		g := c.frame()
		capR, capLeDelta, expDeltaExt := g.ref(), g.ref(), g.ref()
		capR.set(c.bvNum(int64(sbits+2), ebits+2))
		capLeDelta.set(c.ule(capR.get(), c.zeroExtend(2, expDelta.get())))
		expDeltaExt.set(c.zeroExtend(2, expDelta.get()))
		c.simpIte(capLeDelta.get(), capR.get(), expDeltaExt.get(), expDelta)
		expDelta.set(c.extract(ebits-1, 0, expDelta.get()))
		g.done()
	}
	cSig.set(c.concat(cSig.get(), c.bvNum(0, 3)))
	dSig.set(c.concat(dSig.get(), c.bvNum(0, 3)))
	bigDSig := f.ref()
	bigDSig.set(c.concat(dSig.get(), c.bvNum(0, sbits+3)))
	shiftedBig, shiftedDSig, stickyRaw, sticky := f.ref(), f.ref(), f.ref(), f.ref()
	z := c.bvNum(0, (2*(sbits+3))-ebits)
	shiftedBig.set(c.bvLshr(bigDSig.get(), c.concat(z, expDelta.get())))
	shiftedDSig.set(c.extract(2*(sbits+3)-1, sbits+3, shiftedBig.get()))
	stickyRaw.set(c.extract(sbits+2, 0, shiftedBig.get()))
	stickyEq, nilSbit3, oneSbit3 := f.ref(), f.ref(), f.ref()
	nilSbit3.set(c.bvNum(0, sbits+3))
	oneSbit3.set(c.bvNum(1, sbits+3))
	c.simpEq(stickyRaw.get(), nilSbit3.get(), stickyEq)
	c.simpIte(stickyEq.get(), nilSbit3.get(), oneSbit3.get(), sticky)
	shiftedDSig.set(c.bvOr(shiftedDSig.get(), sticky.get()))
	eqSgn := f.ref()
	c.simpEq(cSgn.get(), dSgn.get(), eqSgn)
	cSig.set(c.zeroExtend(2, cSig.get()))
	shiftedDSig.set(c.zeroExtend(2, shiftedDSig.get()))
	sum, cPlusD, cMinusD := f.ref(), f.ref(), f.ref()
	cPlusD.set(c.bvAdd(cSig.get(), shiftedDSig.get()))
	cMinusD.set(c.bvSub(cSig.get(), shiftedDSig.get()))
	c.simpIte(eqSgn.get(), cPlusD.get(), cMinusD.get(), sum)
	signBV, nSum := f.ref(), f.ref()
	signBV.set(c.extract(sbits+4, sbits+4, sum.get()))
	nSum.set(c.bvNeg(sum.get()))
	resSgnC1, resSgnC2, resSgnC3 := f.ref(), f.ref(), f.ref()
	notCSgn, notDSgn, notSignBV := f.ref(), f.ref(), f.ref()
	notCSgn.set(c.bvNot(cSgn.get()))
	notDSgn.set(c.bvNot(dSgn.get()))
	notSignBV.set(c.bvNot(signBV.get()))
	resSgnC1.set(c.bvAnd(notCSgn.get(), dSgn.get(), signBV.get()))
	resSgnC2.set(c.bvAnd(cSgn.get(), notDSgn.get(), notSignBV.get()))
	resSgnC3.set(c.bvAnd(cSgn.get(), dSgn.get()))
	resSgn.set(c.bvOr(resSgnC1.get(), resSgnC2.get(), resSgnC3.get()))
	resSigEq, sigAbs, one1 := f.ref(), f.ref(), f.ref()
	one1.set(c.bvNum(1, 1))
	c.simpEq(signBV.get(), one1.get(), resSigEq)
	c.simpIte(resSigEq.get(), nSum.get(), sum.get(), sigAbs)
	resSig.set(c.extract(sbits+3, 0, sigAbs.get()))
	resExp.set(c.signExtend(2, cExp.get()))
}

// rmArg returns to_app(args[0])->get_arg(0).
func (c *FPA2BVConverter) rmArg(rm ast.ASTHandle) ast.ASTHandle {
	if !c.isBV2RM(rm) {
		c.chk(ast.ErrASTDomain)
	}
	return c.arg(rm, 0)
}

// mkAddDecl is mk_add(f, num, args, result).
