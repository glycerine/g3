// mkDiv is mk_div(s, rm, x, y, result).
func (c *FPA2BVConverter) mkDiv(s ast.ASTHandle, rm, x, y, result *eref) {
	f := c.frame()
	defer f.done()
	nan, nzero, pzero, ninf, pinf := f.ref(), f.ref(), f.ref(), f.ref(), f.ref()
	c.mkNanSort(s, nan)
	c.mkNzeroSort(s, nzero)
	c.mkPzeroSort(s, pzero)
	c.mkNinfSort(s, ninf)
	c.mkPinfSort(s, pinf)
	xIsNan, xIsZero, xIsPos, xIsInf := f.ref(), f.ref(), f.ref(), f.ref()
	yIsNan, yIsZero, yIsPos, yIsInf := f.ref(), f.ref(), f.ref(), f.ref()
	c.mkIsNan(x.get(), xIsNan)
	c.mkIsZero(x.get(), xIsZero)
	c.mkIsPos(x.get(), xIsPos)
	c.mkIsInf(x.get(), xIsInf)
	c.mkIsNan(y.get(), yIsNan)
	c.mkIsZero(y.get(), yIsZero)
	c.mkIsPos(y.get(), yIsPos)
	c.mkIsInf(y.get(), yIsInf)
	c1, c2, c3, c4, c5, c6, c7 := f.ref(), f.ref(), f.ref(), f.ref(), f.ref(), f.ref(), f.ref()
	v1, v2, v3, v4, v5, v6, v7, v8 := f.ref(), f.ref(), f.ref(), f.ref(), f.ref(), f.ref(), f.ref(), f.ref()
	c.simpOr(c1, xIsNan.get(), yIsNan.get())
	v1.set(nan.get())
	c.mkIsPinf(x.get(), c2)
	ySgnInf := f.ref()
	c.mkIte(yIsPos.get(), pinf.get(), ninf.get(), ySgnInf)
	c.mkIte(yIsInf.get(), nan.get(), ySgnInf.get(), v2)
	c.mkIsPinf(y.get(), c3)
	xyZero, signsXor := f.ref(), f.ref()
	c.simpXor(xIsPos.get(), yIsPos.get(), signsXor)
	c.mkIte(signsXor.get(), nzero.get(), pzero.get(), xyZero)
	c.mkIte(xIsInf.get(), nan.get(), xyZero.get(), v3)
	c.mkIsNinf(x.get(), c4)
	negYSgnInf := f.ref()
	c.mkIte(yIsPos.get(), ninf.get(), pinf.get(), negYSgnInf)
	c.mkIte(yIsInf.get(), nan.get(), negYSgnInf.get(), v4)
	c.mkIsNinf(y.get(), c5)
	c.mkIte(xIsInf.get(), nan.get(), xyZero.get(), v5)
	c6.set(yIsZero.get())
	sgnInf := f.ref()
	c.mkIte(signsXor.get(), ninf.get(), pinf.get(), sgnInf)
	c.mkIte(xIsZero.get(), nan.get(), sgnInf.get(), v6)
	c7.set(xIsZero.get())
	c.mkIte(signsXor.get(), nzero.get(), pzero.get(), v7)
	ebits, sbits := c.sortShape(s)
	aSgn, aSig, aExp, aLz, bSgn, bSig, bExp, bLz := f.ref(), f.ref(), f.ref(), f.ref(), f.ref(), f.ref(), f.ref(), f.ref()
	c.unpack(x.get(), aSgn, aSig, aExp, aLz, true)
	c.unpack(y.get(), bSgn, bSig, bExp, bLz, true)
	extraBits := sbits + 2
	aSigExt, bSigExt := f.ref(), f.ref()
	aSigExt.set(c.concat(aSig.get(), c.bvNum(0, sbits+extraBits)))
	bSigExt.set(c.zeroExtend(sbits+extraBits, bSig.get()))
	aExpExt, bExpExt := f.ref(), f.ref()
	aExpExt.set(c.signExtend(2, aExp.get()))
	bExpExt.set(c.signExtend(2, bExp.get()))
	resSgn, resSig, resExp := f.ref(), f.ref(), f.ref()
	resSgn.set(c.bvXor(aSgn.get(), bSgn.get()))
	aLzExt, bLzExt := f.ref(), f.ref()
	aLzExt.set(c.zeroExtend(2, aLz.get()))
	bLzExt.set(c.zeroExtend(2, bLz.get()))
	r := c.bvSub(bExpExt.get(), bLzExt.get())
	l := c.bvSub(aExpExt.get(), aLzExt.get())
	resExp.set(c.bvSub(l, r))
	quotient := f.ref()
	quotient.set(c.must(c.m.MkBitVectorUDivInternal(aSigExt.get(), bSigExt.get())))
	sticky := f.ref()
	sticky.set(c.redor(c.extract(extraBits-2, 0, quotient.get())))
	resSig.set(c.concat(c.extract(extraBits+sbits+1, extraBits-1, quotient.get()), sticky.get()))
	resSigLz := f.ref()
	c.mkLeadingZeros(resSig.get(), sbits+4, resSigLz)
	resSigShiftAmount := f.ref()
	resSigShiftAmount.set(c.bvSub(resSigLz.get(), c.bvNum(1, sbits+4)))
	shiftCond := f.ref()
	shiftCond.set(c.ule(resSigLz.get(), c.bvNum(1, sbits+4)))
	resSigShifted, resExpShifted := f.ref(), f.ref()
	resSigShifted.set(c.bvShl(resSig.get(), resSigShiftAmount.get()))
	resExpShifted.set(c.bvSub(resExp.get(), c.extract(ebits+1, 0, resSigShiftAmount.get())))
	c.simpIte(shiftCond.get(), resSig.get(), resSigShifted.get(), resSig)
	c.simpIte(shiftCond.get(), resExp.get(), resExpShifted.get(), resExp)
	c.round(s, rm, resSgn, resSig, resExp, v8)
	c.mkIte(c7.get(), v7.get(), v8.get(), result)
	c.mkIte(c6.get(), v6.get(), result.get(), result)
	c.mkIte(c5.get(), v5.get(), result.get(), result)
	c.mkIte(c4.get(), v4.get(), result.get(), result)
	c.mkIte(c3.get(), v3.get(), result.get(), result)
	c.mkIte(c2.get(), v2.get(), result.get(), result)
	c.mkIte(c1.get(), v1.get(), result.get(), result)
}

// mkRoundingDecision is mk_rounding_decision(rm, sgn, last, round, sticky);
// res is the returned expr_ref (constructed in place).
func (c *FPA2BVConverter) mkRoundingDecision(rm, sgn, last, rnd, sticky ast.ASTHandle, res *eref) {
	f := c.frame()
	defer f.done()
	rmr, sgnr, lastr, roundr, stickyr := f.ref(), f.ref(), f.ref(), f.ref(), f.ref()
	rmr.set(rm)
	sgnr.set(sgn)
	lastr.set(last)
	roundr.set(rnd)
	stickyr.set(sticky)
	lastOrSticky, roundOrSticky, notLast, notRound, notSticky, notLors, notRors, notSgn := f.ref(), f.ref(), f.ref(), f.ref(), f.ref(), f.ref(), f.ref(), f.ref()
	lastOrSticky.set(c.bvOr(last, sticky))
	roundOrSticky.set(c.bvOr(rnd, sticky))
	notLast.set(c.bvNot(last))
	notRound.set(c.bvNot(rnd))
	notSticky.set(c.bvNot(sticky))
	notLors.set(c.bvNot(lastOrSticky.get()))
	notRors.set(c.bvNot(roundOrSticky.get()))
	notSgn.set(c.bvNot(sgn))
	incTeven, incTaway, incPos, incNeg := f.ref(), f.ref(), f.ref(), f.ref()
	incTeven.set(c.bvNot(c.bvOr(notRound.get(), notLors.get())))
	incTaway.set(rnd)
	incPos.set(c.bvNot(c.bvOr(sgn, notRors.get())))
	incNeg.set(c.bvNot(c.bvOr(notSgn.get(), notRors.get())))
	incC2, incC3, incC4 := f.ref(), f.ref(), f.ref()
	rmIsToNeg, rmIsToPos, rmIsAway, rmIsEven, nil1 := f.ref(), f.ref(), f.ref(), f.ref(), f.ref()
	nil1.set(c.bvNum(0, 1))
	c.mkIsRM(rm, bvRMToNegative, rmIsToNeg)
	c.mkIsRM(rm, bvRMToPositive, rmIsToPos)
	c.mkIsRM(rm, bvRMTiesToAway, rmIsAway)
	c.mkIsRM(rm, bvRMTiesToEven, rmIsEven)
	c.simpIte(rmIsToNeg.get(), incNeg.get(), nil1.get(), incC4)
	c.simpIte(rmIsToPos.get(), incPos.get(), incC4.get(), incC3)
	c.simpIte(rmIsAway.get(), incTaway.get(), incC3.get(), incC2)
	c.simpIte(rmIsEven.get(), incTeven.get(), incC2.get(), res)
}

// round is round(s, rm, sgn, sig, exp, result).
func (c *FPA2BVConverter) round(s ast.ASTHandle, rm, sgn, sig, exp, result *eref) {
	ebits, sbits := c.sortShape(s)
	f := c.frame()
	defer f.done()
	eMin, eMax := f.ref(), f.ref()
	c.mkMinExp(ebits, eMin)
	c.mkMaxExp(ebits, eMax)
	ovf1, eTopThree, sigm1, eEqEmaxAndSigm1, eEqEmax := f.ref(), f.ref(), f.ref(), f.ref(), f.ref()
	e3, ne3, e2, e1, e21, one1, hExp, shExp, thExp := f.ref(), f.ref(), f.ref(), f.ref(), f.ref(), f.ref(), f.ref(), f.ref(), f.ref()
	one1.set(c.bvNum(1, 1))
	hExp.set(c.extract(ebits+1, ebits+1, exp.get()))
	shExp.set(c.extract(ebits, ebits, exp.get()))
	thExp.set(c.extract(ebits-1, ebits-1, exp.get()))
	c.simpEq(hExp.get(), one1.get(), e3)
	c.simpEq(shExp.get(), one1.get(), e2)
	c.simpEq(thExp.get(), one1.get(), e1)
	c.simpOr(e21, e2.get(), e1.get())
	c.simpNot(e3.get(), ne3)
	c.simpAnd(eTopThree, ne3.get(), e21.get())
	extEmax, tSig := f.ref(), f.ref()
	extEmax.set(c.zeroExtend(2, eMax.get()))
	tSig.set(c.extract(sbits+3, sbits+3, sig.get()))
	c.simpEq(extEmax.get(), exp.get(), eEqEmax)
	c.simpEq(tSig.get(), one1.get(), sigm1)
	c.simpAnd(eEqEmaxAndSigm1, eEqEmax.get(), sigm1.get())
	c.simpOr(ovf1, eTopThree.get(), eEqEmaxAndSigm1.get())
	lz := f.ref()
	c.mkLeadingZeros(sig.get(), ebits+2, lz)
	t := f.ref()
	t.set(c.bvAdd(exp.get(), c.bvNum(1, ebits+2)))
	t.set(c.bvSub(t.get(), lz.get()))
	t.set(c.bvSub(t.get(), c.signExtend(2, eMin.get())))
	tiny := f.ref()
	tiny.set(c.sle(t.get(), c.bvNum(int64(^uint32(0)), ebits+2)))
	beta := f.ref()
	one := c.bvNum(1, ebits+2)
	beta.set(c.bvAdd(c.bvSub(exp.get(), lz.get()), one))
	sigma, sigmaAdd := f.ref(), f.ref()
	sigmaAdd.set(c.bvSub(exp.get(), c.signExtend(2, eMin.get())))
	sigmaAdd.set(c.bvAdd(sigmaAdd.get(), c.bvNum(1, ebits+2)))
	c.simpIte(tiny.get(), sigmaAdd.get(), lz.get(), sigma)
	sigSize := c.bvSize(sig.get())
	sigmaSize := ebits + 2
	sigmaNeg, sigmaCap, sigmaNegCapped, sigmaLtZero, sigExt := f.ref(), f.ref(), f.ref(), f.ref(), f.ref()
	rsSig, lsSig, bigShSig, sigmaLeCap := f.ref(), f.ref(), f.ref(), f.ref()
	sigmaNeg.set(c.bvNeg(sigma.get()))
	sigmaCap.set(c.bvNum(int64(sbits+2), sigmaSize))
	sigmaLeCap.set(c.ule(sigmaNeg.get(), sigmaCap.get()))
	c.simpIte(sigmaLeCap.get(), sigmaNeg.get(), sigmaCap.get(), sigmaNegCapped)
	sigmaLtZero.set(c.sle(sigma.get(), c.bvNum(int64(^uint32(0)), sigmaSize)))
	sigExt.set(c.concat(sig.get(), c.bvNum(0, sigSize)))
	rsSig.set(c.bvLshr(sigExt.get(), c.zeroExtend(2*sigSize-sigmaSize, sigmaNegCapped.get())))
	lsSig.set(c.bvShl(sigExt.get(), c.zeroExtend(2*sigSize-sigmaSize, sigma.get())))
	c.simpIte(sigmaLtZero.get(), rsSig.get(), lsSig.get(), bigShSig)
	sigExtractLowBit := (2*sigSize - 1) - (sbits + 2) + 1
	sig.set(c.extract(2*sigSize-1, sigExtractLowBit, bigShSig.get()))
	sticky := f.ref()
	sticky.set(c.redor(c.extract(sigExtractLowBit-1, 0, bigShSig.get())))
	extSticky := f.ref()
	extSticky.set(c.zeroExtend(sbits+1, sticky.get()))
	sig.set(c.bvOr(sig.get(), extSticky.get()))
	extEmin := f.ref()
	extEmin.set(c.zeroExtend(2, eMin.get()))
	c.simpIte(tiny.get(), extEmin.get(), beta.get(), exp)
	rnd, last := f.ref(), f.ref()
	sticky.set(c.extract(0, 0, sig.get()))
	rnd.set(c.extract(1, 1, sig.get()))
	last.set(c.extract(2, 2, sig.get()))
	sig.set(c.extract(sbits+1, 2, sig.get()))
	inc := f.ref()
	c.mkRoundingDecision(rm.get(), sgn.get(), last.get(), rnd.get(), sticky.get(), inc)
	incExt := c.zeroExtend(sbits, inc.get())
	sigExt1 := c.zeroExtend(1, sig.get())
	sig.set(c.bvAdd(sigExt1, incExt))
	sigOvf := f.ref()
	tSig.set(c.extract(sbits, sbits, sig.get()))
	c.simpEq(tSig.get(), one1.get(), sigOvf)
	hallbut1Sig, lallbut1Sig := f.ref(), f.ref()
	hallbut1Sig.set(c.extract(sbits, 1, sig.get()))
	lallbut1Sig.set(c.extract(sbits-1, 0, sig.get()))
	c.simpIte(sigOvf.get(), hallbut1Sig.get(), lallbut1Sig.get(), sig)
	expP1 := f.ref()
	expP1.set(c.bvAdd(exp.get(), c.bvNum(1, ebits+2)))
	c.simpIte(sigOvf.get(), expP1.get(), exp.get(), exp)
	biasedExp := f.ref()
	c.mkBias(c.extract(ebits-1, 0, exp.get()), biasedExp)
	preOvf2, ovf2, ovf, expRedand, pem2m1 := f.ref(), f.ref(), f.ref(), f.ref(), f.ref()
	expRedand.set(c.redand(biasedExp.get()))
	c.simpEq(expRedand.get(), one1.get(), preOvf2)
	c.simpAnd(ovf2, sigOvf.get(), preOvf2.get())
	pem2m1.set(c.bvNumBig(powers2m1(ebits-2, false), ebits))
	c.simpIte(ovf2.get(), pem2m1.get(), biasedExp.get(), biasedExp)
	c.simpOr(ovf, ovf1.get(), ovf2.get())
	topExp, botExp := f.ref(), f.ref()
	c.mkTopExp(ebits, topExp)
	c.mkBotExp(ebits, botExp)
	nil1 := f.ref()
	nil1.set(c.bvNum(0, 1))
	rmIsToZero, rmIsToNeg, rmIsToPos, rmZeroOrNeg, rmZeroOrPos := f.ref(), f.ref(), f.ref(), f.ref(), f.ref()
	c.mkIsRM(rm.get(), bvRMToZero, rmIsToZero)
	c.mkIsRM(rm.get(), bvRMToNegative, rmIsToNeg)
	c.mkIsRM(rm.get(), bvRMToPositive, rmIsToPos)
	c.simpOr(rmZeroOrNeg, rmIsToZero.get(), rmIsToNeg.get())
	c.simpOr(rmZeroOrPos, rmIsToZero.get(), rmIsToPos.get())
	sgnIsZero, zero1 := f.ref(), f.ref()
	zero1.set(c.bvNum(0, 1))
	c.simpEq(sgn.get(), zero1.get(), sgnIsZero)
	maxSig, maxExp, infSig, infExp := f.ref(), f.ref(), f.ref(), f.ref()
	maxSig.set(c.bvNumBig(powers2m1(sbits-1, false), sbits-1))
	lowBit := c.bvNum(0, 1)
	highBits := c.bvNumBig(powers2m1(ebits-1, false), ebits-1)
	maxExp.set(c.concat(highBits, lowBit))
	infSig.set(c.bvNum(0, sbits-1))
	infExp.set(topExp.get())
	ovflExp, maxInfExpNeg, maxInfExpPos, nDCheck, nDExp := f.ref(), f.ref(), f.ref(), f.ref(), f.ref()
	c.simpIte(rmZeroOrPos.get(), maxExp.get(), infExp.get(), maxInfExpNeg)
	c.simpIte(rmZeroOrNeg.get(), maxExp.get(), infExp.get(), maxInfExpPos)
	c.simpIte(sgnIsZero.get(), maxInfExpPos.get(), maxInfExpNeg.get(), ovflExp)
	tSig.set(c.extract(sbits-1, sbits-1, sig.get()))
	c.simpEq(tSig.get(), nil1.get(), nDCheck)
	c.simpIte(nDCheck.get(), botExp.get(), biasedExp.get(), nDExp)
	c.simpIte(ovf.get(), ovflExp.get(), nDExp.get(), exp)
	maxInfSigNeg, maxInfSigPos, ovflSig, restSig := f.ref(), f.ref(), f.ref(), f.ref()
	c.simpIte(rmZeroOrPos.get(), maxSig.get(), infSig.get(), maxInfSigNeg)
	c.simpIte(rmZeroOrNeg.get(), maxSig.get(), infSig.get(), maxInfSigPos)
	c.simpIte(sgnIsZero.get(), maxInfSigPos.get(), maxInfSigNeg.get(), ovflSig)
	restSig.set(c.extract(sbits-2, 0, sig.get()))
	c.simpIte(ovf.get(), ovflSig.get(), restSig.get(), sig)
	resSgn, resSig, resExp := f.ref(), f.ref(), f.ref()
	resSgn.set(sgn.get())
	resSig.set(sig.get())
	resExp.set(exp.get())
	result.set(c.mkFP(resSgn.get(), resExp.get(), resSig.get()))
}
