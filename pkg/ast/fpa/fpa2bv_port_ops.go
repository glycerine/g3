// bvult is the BVULT(X, Y, R) macro.
func (c *FPA2BVConverter) bvult(x, y ast.ASTHandle, r *eref) {
	f := c.frame()
	defer f.done()
	t := f.ref()
	t.set(c.ule(y, x))
	c.simpNot(t.get(), r)
}

// mkRemDecl is mk_rem(f, num, args, result).
