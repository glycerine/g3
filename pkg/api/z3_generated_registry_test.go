// Source registry generated from src/api/z3_api.h with scripts/update_api.py.
// This locks the exact native command ID/name mapping to the Go handlers.
func TestGeneratedAPICommandRegistryMatchesSource(t *testing.T) {
	r, err := NewZ3Replayer(strings.NewReader(""), io.Discard)
	if err != nil {
		t.Fatal(err)
	}
	defer func() {
		if err := r.Close(); err != nil {
			t.Error(err)
		}
	}()
	registrars := []func(*Z3Replayer) error{
		RegisterZ3GeneratedGlobalCommands,
		RegisterZ3GeneratedConfigCommands,
		RegisterZ3GeneratedContextCommands,
		RegisterZ3GeneratedSymbolCommands,
		RegisterZ3GeneratedProcessCommands,
		RegisterZ3GeneratedASTCommands,
		RegisterZ3GeneratedParameterCommands,
		RegisterZ3GeneratedModelCommands,
		RegisterZ3GeneratedSolverCommands,
	}
	for _, register := range registrars {
		if err := register(r); err != nil {
			t.Fatal(err)
		}
	}
	if len(r.commands) != len(sourceAPICommandRegistry) {
		t.Fatalf("registered %d commands, source has %d", len(r.commands), len(sourceAPICommandRegistry))
	}
	for _, expected := range sourceAPICommandRegistry {
		got, ok := r.commands[expected.id]
		if !ok || got.name != expected.name {
			t.Errorf("command %d = %q (registered %t), want %q", expected.id, got.name, ok, expected.name)
		}
	}
}

