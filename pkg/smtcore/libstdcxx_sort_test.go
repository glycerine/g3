// =========================================================================
// !!! THIS TEST MUST STAY GREEN: it proves g3 matches z3's libstdc++ sort !!!
// =========================================================================
//
// TestLibstdcxxSortMatchesControl replays the scenarios of
// src/test/stl_sort_order_control.cpp through libstdcxxSortAtoms and
// compares each resulting tie order with the real libstdc++ (GCC 13)
// std::sort output recorded in test_vectors/libstdcxx_sort_order.txt.
// TestLibstdcxxSortLRABoundsMatchesControl replays the same scenarios
// through libstdcxxSortLRABounds (*smtLRABound, theory_lra's
// compare_bounds).
//
// Why it matters: both approved call sites, theory_arith's and theory_lra's
// flush_bound_axioms, sort bound atoms with std::sort and a comparator
// (compare_atoms / compare_bounds) that compares only the bound value, so
// atoms with the same bound are ties. With more than 16 atoms introsort
// permutes those ties, and that order decides bound-axiom clause creation
// and then the search (theory_arith fuzz seeds q_2119, q_3063, q_3110,
// old_q_515 diverged without it; q_3110 never finished). g3 reproduces
// std::sort exactly via libstdcxx_sort.go, a user-approved (2026-11-13)
// exception to the no-STL-port rule, extended the same day to theory_lra.
// If these tests fail, flush_bound_axioms no longer matches z3 4.7.1. Fix
// the port, never the expectations: the expected file may only be
// regenerated by recompiling and rerunning the C++ control program (see its
// header). Replacing the port with sort.SliceStable makes both tests fail
// (checked 2026-11-13), so they really guard the order.
func TestLibstdcxxSortMatchesControl(t *testing.T) {
	// Same comparator shape as compare_atoms at the flushBoundAxioms call
	// site: threshold only; the atom's boolean var carries the tag.
	runLibstdcxxSortControl(t, func(keys []uint32) []int {
		atoms := make([]*smtArithmeticAtom, len(keys))
		for i, k := range keys {
			atoms[i] = &smtArithmeticAtom{boolean: SMTBoolVar(i)}
			atoms[i].threshold = newSMTArithmeticValue(new(big.Rat).SetInt64(int64(k)), nil)
		}
		libstdcxxSortAtoms(atoms, smtCompareAtomsLess)
		order := make([]int, len(atoms))
		for i, a := range atoms {
			order[i] = int(a.boolean)
		}
		return order
	})
}

// TestLibstdcxxSortLRABoundsMatchesControl: theory_lra's compare_bounds
// (value only). Alternating upper/lower kinds mimic (<= x c)/(>= x c) ties;
// the bound's boolean var carries the tag. See the comment above.
func TestLibstdcxxSortLRABoundsMatchesControl(t *testing.T) {
	runLibstdcxxSortControl(t, func(keys []uint32) []int {
		bounds := make([]*smtLRABound, len(keys))
		for i, k := range keys {
			bounds[i] = &smtLRABound{boolean: int32(i), upper: i%2 == 1}
			bounds[i].value.SetInt64(int64(k))
		}
		libstdcxxSortLRABounds(bounds)
		order := make([]int, len(bounds))
		for i, b := range bounds {
			order[i] = int(b.boolean)
		}
		return order
	})
}

func runLibstdcxxSortControl(t *testing.T, sortTags func(keys []uint32) []int) {
	t.Helper()
	f, err := os.Open("test_vectors/libstdcxx_sort_order.txt")
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	want := map[string]string{}
	inputs := map[string][]uint32{}
	scanner := bufio.NewScanner(f)
	scanner.Buffer(make([]byte, 1<<20), 1<<24)
	for scanner.Scan() {
		fields := strings.Fields(scanner.Text())
		if len(fields) < 2 {
			continue
		}
		switch fields[0] {
		case "order":
			want[fields[1]] = strings.Join(fields[2:], " ")
		case "input":
			var keys []uint32
			for _, s := range fields[2:] {
				k, err := strconv.ParseUint(s, 10, 32)
				if err != nil {
					t.Fatal(err)
				}
				keys = append(keys, uint32(k))
			}
			inputs[fields[1]] = keys
		}
	}
	if err = scanner.Err(); err != nil {
		t.Fatal(err)
	}
	state := uint64(88172645463325252)
	next := func() uint32 {
		state = state*6364136223846793005 + 1442695040888963407
		return uint32(state >> 33)
	}
	checked := 0
	check := func(tag string, keys []uint32) {
		t.Helper()
		var b strings.Builder
		for i, tagIndex := range sortTags(keys) {
			if i > 0 {
				b.WriteByte(' ')
			}
			fmt.Fprintf(&b, "%d", tagIndex)
		}
		w, ok := want[tag]
		if !ok {
			t.Fatalf("control output has no %s", tag)
		}
		if got := b.String(); got != w {
			t.Fatalf("%s:\n got %s\nwant %s", tag, got, w)
		}
		checked++
	}
	for _, r := range []uint32{1, 3, 20} {
		for n := 0; n <= 300; n++ {
			keys := make([]uint32, n)
			for i := range keys {
				keys[i] = next() % r
			}
			check(fmt.Sprintf("rand_r%d_n%d", r, n), keys)
		}
	}
	for n := 0; n <= 300; n += 7 {
		for d := 1; d <= 3; d += 2 {
			asc := make([]uint32, n)
			desc := make([]uint32, n)
			for i := 0; i < n; i++ {
				asc[i] = uint32(i / d)
				desc[i] = uint32((n - i) / d)
			}
			check(fmt.Sprintf("asc_d%d_n%d", d, n), asc)
			check(fmt.Sprintf("desc_d%d_n%d", d, n), desc)
		}
	}
	for n := 2; n <= 120; n++ {
		keys := make([]uint32, n)
		for i := range keys {
			keys[i] = uint32(i/2) % (1 + next()%9)
		}
		check(fmt.Sprintf("pairs_n%d", n), keys)
	}
	heapBefore := libstdcxxSortHeapFallbacks
	for _, n := range []int{40, 64, 100, 200, 257, 300} {
		tag := fmt.Sprintf("killer_n%d", n)
		keys, ok := inputs[tag]
		if !ok || len(keys) != n {
			t.Fatalf("control output has no input for %s", tag)
		}
		check(tag, keys)
	}
	if libstdcxxSortHeapFallbacks == heapBefore {
		t.Fatalf("killer inputs never reached the heap-sort fallback")
	}
	if checked != len(want) {
		t.Fatalf("checked %d of %d control lines", checked, len(want))
	}
}
