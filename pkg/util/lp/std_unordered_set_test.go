// =========================================================================
// !!! THIS TEST MUST STAY GREEN: it proves g3 matches z3's C++ container !!!
// =========================================================================
//
// TestStdUnorderedUintSetMatchesLibstdcxx replays the scenarios of
// src/test/stl_unordered_set_order_control.cpp and compares each iteration
// order and bucket count with the libstdc++ output recorded in
// test_vectors/libstdcxx_unordered_set_order.txt.
//
// Why it matters: lu.h's add_last_rows_to_B replaces LU basis columns in the
// iteration order of a std::unordered_set<unsigned> (and stops when the
// factorization degenerates). g3 reproduces that order with
// StdUnorderedUintSet, a user-approved (2026-11-12) exception to the
// no-STL-port rule. If this test fails, g3's LP factorization order no
// longer matches z3 4.7.1, and solver-6 (lar_solver) runs can diverge from
// the fork. Fix the emulation, never the expectations: the expected file may
// only be regenerated by recompiling and rerunning the C++ control program
// (see its header). A reversed or sorted Keys() makes this test fail
// (checked 2026-11-12), so it really guards the order.
func TestStdUnorderedUintSetMatchesLibstdcxx(t *testing.T) {
	f, err := os.Open("test_vectors/libstdcxx_unordered_set_order.txt")
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	want := map[string]string{}
	scanner := bufio.NewScanner(f)
	scanner.Buffer(make([]byte, 1<<20), 1<<24)
	for scanner.Scan() {
		fields := strings.Fields(scanner.Text())
		if len(fields) >= 3 && fields[0] == "order" {
			want[fields[1]] = strings.Join(fields[2:], " ")
		}
	}
	if err = scanner.Err(); err != nil {
		t.Fatal(err)
	}
	state := uint64(88172645463325252)
	next := func() uint32 {
		state = state*6364136223846793005 + 1442695040888963407
		return uint32(state >> 33)
	}
	checked := 0
	check := func(tag string, s *StdUnorderedUintSet) {
		t.Helper()
		var b strings.Builder
		fmt.Fprintf(&b, "%d", s.table.BucketCount())
		for _, k := range s.Keys() {
			fmt.Fprintf(&b, " %d", k)
		}
		w, ok := want[tag]
		if !ok {
			t.Fatalf("control output has no %s", tag)
		}
		if got := b.String(); got != w {
			t.Fatalf("%s:\n got %s\nwant %s", tag, got, w)
		}
		checked++
	}
	s := NewStdUnorderedUintSet()
	for k := uint32(0); k < 40; k++ {
		s.Insert(k)
		check(fmt.Sprintf("asc%d", k), s)
	}
	for trial := 0; trial < 200; trial++ {
		s := NewStdUnorderedUintSet()
		rows := 1 + next()%6
		width := 2 + next()%60
		for r := uint32(0); r < rows; r++ {
			cells := 1 + next()%12
			for c := uint32(0); c < cells; c++ {
				s.Insert(next() % width)
			}
		}
		check(fmt.Sprintf("rows%d", trial), s)
	}
	s = NewStdUnorderedUintSet()
	for i := 1; i <= 6000; i++ {
		s.Insert(next() % 20000)
		if i%1000 == 0 {
			check(fmt.Sprintf("large%d", i), s)
		}
	}
	if checked != len(want) {
		t.Fatalf("checked %d of %d control lines", checked, len(want))
	}
}
